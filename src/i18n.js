/**
 * English stays the default. A saved choice wins. Otherwise offer the first
 * supported language that is not English, and stop if English is preferred first.
 */
export function languageOffer(languages, savedLang) {
  if (UI_LANGS.includes(savedLang)) return null;
  const offered = UI_LANGS.filter((lang) => lang !== 'en');
  const list = Array.isArray(languages) ? languages : [];
  for (const code of list) {
    const base = String(code || '').toLowerCase().split('-')[0];
    if (!base) continue;
    if (base === 'en') return null;
    if (offered.includes(base)) return base;
  }
  return null;
}

export function translate(lang, key, vars) {
  const pack = STRINGS[lang] || STRINGS.en;
  let text = pack[key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
